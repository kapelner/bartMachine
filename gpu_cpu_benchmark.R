#!/usr/bin/env Rscript
# =============================================================================
# gpu_cpu_benchmark.R — bartMachine GPU vs CPU prediction benchmark
#
# For every GPU-accelerated prediction path, measures:
#   - median wall-clock time over N_REPS runs (CPU and GPU separately)
#   - max absolute difference between CPU and GPU outputs (correctness check)
#
# GPU path activates only when ALL of the following are true:
#   (1) bartMachine was compiled with TornadoVM (GpuForestPredictor.class is
#       present in bart_java.jar — rebuild with TORNADO_SDK set), AND
#   (2) a CUDA / OpenCL GPU device is detected at runtime, AND
#   (3) n_test >= 1000 (hard-coded threshold in bartMachine Java source)
#
# If no GPU is detected both columns show CPU timing and the script says so.
#
# GPU-accelerated functions benchmarked:
#   Regression:
#     predict()                     (Java: getPosteriorMeanForPrediction)
#     bart_machine_get_posterior()  (Java: getGibbsSamplesForPrediction)
#     calc_credible_intervals()     (Java: getCredibleIntervalsForPrediction)
#   Classification:
#     predict(type="prob")          (Java: getPosteriorMeanForPrediction override)
#     bart_machine_get_posterior()  (Java: getGibbsSamplesForPrediction  override)
#     calc_credible_intervals()     (Java: getCredibleIntervalsForPrediction override)
#
# CPU-only (included for context, no GPU path implemented):
#     calc_prediction_intervals()   (Java: getPredictionIntervalsForPrediction)
#
# ---------------------------------------------------------------------------
# Usage — MUST be run as a fresh Rscript process so JVM flags take effect:
#
#   Rscript gpu_cpu_benchmark.R                               # defaults
#   Rscript gpu_cpu_benchmark.R N_TEST                        # e.g. 10000
#   Rscript gpu_cpu_benchmark.R N_TEST N_TRAIN                # e.g. 10000 3000
#   Rscript gpu_cpu_benchmark.R N_TEST N_TRAIN N_TREES        # e.g. 10000 3000 100
#   Rscript gpu_cpu_benchmark.R N_TEST N_TRAIN N_TREES N_SAMP # e.g. 10000 3000 100 2000
#
# ---------------------------------------------------------------------------
# JVM / TornadoVM setup:
#
#   CPU-only (no GPU):
#     No setup needed — the script sets the required base flags automatically.
#
#   GPU (TornadoVM):
#     Set TORNADO_SDK to the TornadoVM install directory before running.
#     The script reads $TORNADO_SDK/tornado-argfile which contains the complete,
#     version-correct set of JVM flags for your TornadoVM build.
#
#     Alternatively, follow the README instructions and set java.parameters
#     manually in a .Rprofile or wrapper script before calling Rscript.
#     Example for NVIDIA (PTX backend):
#       options(java.parameters = c("-Xmx20g",
#           "--add-modules=jdk.incubator.vector", "-XX:+UseZGC",
#           "-Dtornado.backends=ptx-backend",
#           "--add-opens=java.base/jdk.internal.misc=ALL-UNNAMED",
#           "--add-opens=java.base/jdk.internal.loader=ALL-UNNAMED"))
#     See README for Intel, AMD, OpenCL, and Apple Metal variants.
#
# Keep this script — run it on new hardware to characterise GPU speedup.
# =============================================================================

# ---------------------------------------------------------------------------
# JVM parameters — set BEFORE any library() call so rJava starts JVM correctly
# ---------------------------------------------------------------------------
.build_jvm_params <- function() {
  # Base flags required by bartMachine >= 1.4 regardless of GPU
  base <- c(
    "-Xmx8g",
    "--add-modules=jdk.incubator.vector",
    "-XX:+UseZGC"
  )

  # If java.parameters is already set (e.g. user ran from an .Rprofile wrapper)
  # then honour it and add only the incubator flag if missing.
  existing <- getOption("java.parameters")
  if (!is.null(existing)) {
    if (!any(grepl("incubator.vector", existing))) {
      existing <- c(existing, "--add-modules=jdk.incubator.vector")
    }
    return(existing)
  }

  # Auto-detect TornadoVM flags from $TORNADO_SDK/tornado-argfile.
  # The argfile is generated by the TornadoVM installer and contains the
  # complete, version-correct set of module-path, upgrade-module-path,
  # add-exports, add-opens, and Dtornado.* flags for the local build.
  tornado_sdk <- Sys.getenv("TORNADO_SDK", unset = "")
  if (nzchar(tornado_sdk)) {
    argfile <- file.path(tornado_sdk, "tornado-argfile")
    if (file.exists(argfile)) {
      lines         <- readLines(argfile, warn = FALSE)
      tornado_flags <- lines[nzchar(trimws(lines)) & !startsWith(trimws(lines), "#")]

      # Drop flags invalid for embedded JNI use:
      #   -server      : removed in Java 11+; crashes JNI_CreateJavaVM
      #   GC / heap    : we supply our own (-XX:+UseZGC, -Xmx8g)
      # Keep --enable-preview: TornadoVM JARs are compiled with preview features.
      tornado_flags <- tornado_flags[!grepl(
        "^-server$|UseParallelGC|UseZGC|^-Xmx|^-Xms",
        tornado_flags)]

      # The argfile uses the Java-launcher space-separated format:
      #   --module-path .:/path/to/tornado
      # rJava passes each vector element as a single JNI option string, which
      # requires the equals-sign format understood by JNI_CreateJavaVM:
      #   --module-path=.:/path/to/tornado
      tornado_flags <- sub("^(--[a-zA-Z-]+) (.+)$", "\\1=\\2", tornado_flags)

      # TornadoVM's ASMClassVisitor uses ClassLoader.getSystemClassLoader() to
      # read class bytecodes for GPU kernel compilation. rJava adds bart_java.jar
      # to a child URLClassLoader after JVM startup, so the system classloader
      # can't find it. Fix: -javaagent: causes the JVM to add the agent jar to
      # the system classpath *before* any user classes load (Java spec guarantee).
      bart_jar <- system.file("java", "bart_java.jar", package = "bartMachine")
      agent_flag <- if (nzchar(bart_jar) && file.exists(bart_jar))
                      paste0("-javaagent:", bart_jar)
                    else
                      character(0)

      return(c(base, tornado_flags, agent_flag))
    }
    message("TORNADO_SDK is set but $TORNADO_SDK/tornado-argfile not found.")
  }

  base
}

options(java.parameters = .build_jvm_params())

suppressPackageStartupMessages({
  library(bartMachine)
  library(rJava)
})

# ---------------------------------------------------------------------------
# Configuration — override via positional command-line arguments
# ---------------------------------------------------------------------------
args    <- commandArgs(trailingOnly = TRUE)
N_TEST  <- as.integer(if (length(args) >= 1) args[[1]] else  5000)  # test-set size
N_TRAIN <- as.integer(if (length(args) >= 2) args[[2]] else  2000)  # training-set size
N_TREES <- as.integer(if (length(args) >= 3) args[[3]] else    50)  # BART trees
N_SAMP  <- as.integer(if (length(args) >= 4) args[[4]] else  1000)  # posterior samples
P       <- 10L    # predictors
N_BURN  <- 250L   # burn-in iterations
N_REPS  <- 3L     # timed repetitions per benchmark; median is reported
SEED    <- 42L
# Regression kernels (+, -, * only) match to ~1e-14; classification kernels use
# Math.exp() which GPU PTX transcendental functions implement with slightly
# looser precision (~1e-7 typical).  1e-6 covers both.
DIFF_TOL <- 1e-6

if (N_TEST < 1000L) {
  stop("N_TEST must be >= 1000 — the Java GPU path does not activate for smaller batches.")
}

set.seed(SEED)
set_bart_machine_num_cores(parallel::detectCores())

# ---------------------------------------------------------------------------
# Helper: toggle use_gpu on the underlying Java object.
# This does not change model parameters — only the prediction dispatch path.
# ---------------------------------------------------------------------------
set_gpu <- function(bm, flag) {
  .jcall(bm$java_bart_machine, "V", "setUseGpu", as.logical(flag))
}

# ---------------------------------------------------------------------------
# Helper: median wall-clock time over `reps` calls to fn()
# ---------------------------------------------------------------------------
time_median <- function(fn, reps = N_REPS) {
  times <- numeric(reps)
  for (i in seq_len(reps)) {
    gc(verbose = FALSE)
    t0      <- proc.time()[["elapsed"]]
    fn()
    times[i] <- proc.time()[["elapsed"]] - t0
  }
  median(times)
}

# ---------------------------------------------------------------------------
# Core benchmark runner
#
# For GPU-accelerated functions:
#   1. One warm-up call in each mode (primes JVM JIT and TornadoVM PTX/OpenCL
#      kernel compilation so those costs are excluded from the timed runs)
#   2. Capture reference outputs in CPU mode and GPU mode
#   3. Time N_REPS calls in each mode; report medians
#   4. Compute max absolute difference for correctness verification
#
# For CPU-only functions: one timing column, no output diff.
# ---------------------------------------------------------------------------
bench <- function(label, fn, bm, gpu_accelerated = TRUE) {
  if (gpu_accelerated) {
    set_gpu(bm, FALSE); invisible(fn())   # CPU warm-up
    set_gpu(bm, TRUE);  invisible(fn())   # GPU warm-up (compiles PTX/SPIR-V kernel)

    set_gpu(bm, FALSE)
    cpu_out  <- fn()
    cpu_time <- time_median(fn)

    set_gpu(bm, TRUE)
    gpu_out  <- fn()
    gpu_time <- time_median(fn)

    list(
      label        = label,
      cpu_s        = cpu_time,
      gpu_s        = gpu_time,
      speedup      = cpu_time / gpu_time,
      max_abs_diff = max(abs(as.vector(cpu_out) - as.vector(gpu_out)))
    )
  } else {
    invisible(fn())
    list(
      label        = label,
      cpu_s        = time_median(fn),
      gpu_s        = NA_real_,
      speedup      = NA_real_,
      max_abs_diff = NA_real_
    )
  }
}

# ---------------------------------------------------------------------------
# Print helpers
# ---------------------------------------------------------------------------
SEP80 <- strrep("─", 80)

section_header <- function(...) {
  title <- paste0(...)
  cat("\n", SEP80, "\n  ", title, "\n", SEP80, "\n", sep = "")
}

print_table <- function(results, gpu_present) {
  cat(sprintf("  %-44s  %8s  %8s  %9s  %12s\n",
              "Function", "CPU (s)", "GPU (s)", "Speedup", "MaxAbsDiff"))
  cat("  ", strrep("-", 76), "\n", sep = "")

  for (r in results) {
    if (!is.na(r$gpu_s)) {
      gpu_s_str   <- sprintf("%8.3f", r$gpu_s)
      speedup_str <- if (gpu_present) sprintf("%8.2fx", r$speedup) else "  no GPU *"
    } else {
      gpu_s_str   <- "      --"
      speedup_str <- "       --"
    }

    diff_str <- if (is.na(r$max_abs_diff)) "          --" else
                formatC(r$max_abs_diff, format = "e", digits = 2, width = 12)

    flag <- if (!is.na(r$max_abs_diff) && r$max_abs_diff > DIFF_TOL) " !" else ""

    cat(sprintf("  %-44s  %8.3f  %s  %s  %s%s\n",
                r$label, r$cpu_s, gpu_s_str, speedup_str, diff_str, flag))
  }
}

# ---------------------------------------------------------------------------
# Detect GPU availability (static field set once at class-load time in Java)
# ---------------------------------------------------------------------------
gpu_present <- tryCatch(
  .jfield("bartMachine.GpuPredictorBridge", "Z", "GPU_AVAILABLE"),
  error = function(e) FALSE
)

# ---------------------------------------------------------------------------
# Banner
# ---------------------------------------------------------------------------
cat("\n", strrep("=", 80), "\n", sep = "")
cat("  bartMachine GPU vs CPU Prediction Benchmark\n")
cat(strrep("=", 80), "\n\n", sep = "")
cat(sprintf("  R version   : %s\n", R.version.string))
cat(sprintf("  Java        : %s\n",
            tryCatch(.jcall("java.lang.System", "S", "getProperty", "java.version"),
                     error = function(e) Sys.getenv("JAVA_HOME", unset = "unknown"))))
sdk_val <- Sys.getenv("TORNADO_SDK", unset = "")
cat(sprintf("  TORNADO_SDK : %s\n", if (nzchar(sdk_val)) sdk_val else "(not set)"))
cat(sprintf("  GPU found   : %s\n",
            if (gpu_present) "YES" else
              "NO  (both columns will reflect CPU; GPU column = CPU fallback)"))
cat(sprintf("  N_TRAIN=%-5d  N_TEST=%-6d  P=%-3d  N_TREES=%-4d  N_SAMP=%-5d  N_REPS=%d\n\n",
            N_TRAIN, N_TEST, P, N_TREES, N_SAMP, N_REPS))

# ---------------------------------------------------------------------------
# Synthetic data
#   Regression target:     f(x) = x1 + x2 + x3 + N(0, 0.5)
#   Classification target: binarised median-split of regression target
# ---------------------------------------------------------------------------
X_train <- as.data.frame(matrix(rnorm(N_TRAIN * P), N_TRAIN, P))
y_reg   <- rowSums(X_train[, 1:3]) + rnorm(N_TRAIN, sd = 0.5)
y_cls   <- factor(as.integer(y_reg > median(y_reg)))
X_test  <- as.data.frame(matrix(rnorm(N_TEST * P), N_TEST, P))

# ---------------------------------------------------------------------------
# Train models
# GPU flag is irrelevant during training — MCMC sampling always runs on CPU.
# It only controls prediction dispatch in predict / get_posterior / etc.
# ---------------------------------------------------------------------------
cat("Training regression model ...\n")
bm_reg <- bartMachine(
  X = X_train, y = y_reg,
  num_trees                    = N_TREES,
  num_burn_in                  = N_BURN,
  num_iterations_after_burn_in = N_SAMP,
  verbose = FALSE
)

cat("Training classification model ...\n")
bm_cls <- bartMachine(
  X = X_train, y = y_cls,
  num_trees                    = N_TREES,
  num_burn_in                  = N_BURN,
  num_iterations_after_burn_in = N_SAMP,
  verbose = FALSE
)

cat("Models trained. Starting benchmarks ...\n")

# ---------------------------------------------------------------------------
# Regression benchmarks
# ---------------------------------------------------------------------------
section_header("Regression benchmarks  (N_TEST = ", N_TEST, " records)")

reg_results <- list(

  bench(
    "predict()  [posterior mean]",
    function() predict(bm_reg, X_test, verbose = FALSE),
    bm_reg
  ),

  bench(
    "bart_machine_get_posterior()  [all samples]",
    function() bart_machine_get_posterior(bm_reg, X_test, verbose = FALSE)$y_hat_posterior_samples,
    bm_reg
  ),

  bench(
    "calc_credible_intervals()",
    function() calc_credible_intervals(bm_reg, X_test),
    bm_reg
  ),

  bench(
    "calc_prediction_intervals()  [CPU only]",
    function() calc_prediction_intervals(bm_reg, X_test),
    bm_reg,
    gpu_accelerated = FALSE
  )
)

print_table(reg_results, gpu_present)

# ---------------------------------------------------------------------------
# Classification benchmarks
# ---------------------------------------------------------------------------
section_header("Classification benchmarks  (N_TEST = ", N_TEST, " records)")

cls_results <- list(

  bench(
    "predict(type='prob')  [posterior mean prob]",
    function() predict(bm_cls, X_test, type = "prob", verbose = FALSE),
    bm_cls
  ),

  bench(
    "bart_machine_get_posterior()  [all prob samples]",
    function() bart_machine_get_posterior(bm_cls, X_test, verbose = FALSE)$y_hat_posterior_samples,
    bm_cls
  ),

  bench(
    "calc_credible_intervals()",
    function() calc_credible_intervals(bm_cls, X_test),
    bm_cls
  )
)

print_table(cls_results, gpu_present)

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
all_results  <- c(reg_results, cls_results)
gpu_results  <- Filter(function(r) !is.na(r$speedup), all_results)
any_mismatch <- any(sapply(gpu_results, function(r) r$max_abs_diff > DIFF_TOL))
speedups     <- sapply(gpu_results, `[[`, "speedup")

cat("\n", strrep("=", 80), "\n", sep = "")
cat("  Summary\n")
cat(strrep("=", 80), "\n", sep = "")

if (!gpu_present) {
  cat("\n  No GPU was detected — both columns above reflect CPU execution.\n")
  cat("\n  To enable GPU acceleration:\n")
  cat("    1. Install TornadoVM: https://github.com/beehive-lab/TornadoVM\n")
  cat("    2. export TORNADO_SDK=/path/to/tornadovm  (in your shell profile)\n")
  cat("    3. Rebuild the bartMachine jar:\n")
  cat("         ant clean      (TORNADO_SDK auto-detected)\n")
  cat("       or:\n")
  cat("         ant clean -Dtornadovm.jar=$TORNADO_SDK/share/java/tornado/tornado-api*.jar\n")
  cat("    4. Re-run:  Rscript gpu_cpu_benchmark.R\n\n")
  cat("    * GPU column shows CPU fallback timing when no GPU is detected.\n\n")
} else {
  finite_speedups <- speedups[is.finite(speedups) & speedups > 0]
  geo_mean <- exp(mean(log(finite_speedups)))
  cat(sprintf("\n  Geometric mean speedup across %d GPU-accelerated functions: %.2fx\n",
              length(gpu_results), geo_mean))
  cat(sprintf("  Best  : %.2fx  (%s)\n",
              max(speedups), gpu_results[[which.max(speedups)]]$label))
  cat(sprintf("  Worst : %.2fx  (%s)\n\n",
              min(speedups), gpu_results[[which.min(speedups)]]$label))
}

cat("  Output correctness — max |CPU - GPU| per GPU-accelerated function:\n")
for (r in gpu_results) {
  flag <- if (r$max_abs_diff > DIFF_TOL) "  <-- MISMATCH" else ""
  cat(sprintf("    %-44s %s%s\n", r$label,
              formatC(r$max_abs_diff, format = "e", digits = 2), flag))
}

if (any_mismatch) {
  cat(sprintf("\n  WARNING: mismatch detected (tolerance = %.0e).\n", DIFF_TOL))
} else {
  cat(sprintf("\n  All GPU outputs match CPU outputs (tolerance = %.0e). OK\n", DIFF_TOL))
}

cat(strrep("=", 80), "\n\n", sep = "")
